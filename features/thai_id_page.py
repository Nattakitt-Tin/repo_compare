def generate_thai_id() -> str:
    digits = [random.randint(0, 9) for _ in range(12)]
    checksum = sum(d * (13 - i) for i, d in enumerate(digits, start=1))
    check_digit = (11 - (checksum % 11)) % 10
    digits.append(check_digit)
    return "".join(str(d) for d in digits)


def get_province_info(citizen_id: str):
    code = citizen_id[1:3]
    return province_region_map.get(code, ("ไม่ทราบ", "ไม่ทราบ"))


def show():
    st.header("🎲 สุ่มเลขบัตรประชาชนไทย")
    count = st.number_input("จำนวนเลขที่ต้องการสุ่ม", min_value=1, max_value=20, value=1, step=1)
    if st.button("Generate", key="gen_thai_id"):
        st.session_state.generated_ids = [generate_thai_id() for _ in range(count)]
        for k in list(st.session_state.keys()):
            if k.startswith("show_info_"):
                del st.session_state[k]

    ids = st.session_state.get("generated_ids", [])
    for idx, cid in enumerate(ids):
        col1, col2 = st.columns([3, 1])
        col1.write(cid)
        info_key = f"info_{idx}"
        if col2.button("Information", key=info_key):
            st.session_state[f"show_info_{idx}"] = not st.session_state.get(f"show_info_{idx}", False)
        if st.session_state.get(f"show_info_{idx}", False):
            prov, region = get_province_info(cid)
            st.info(f"จังหวัด: {prov} | ภาค: {region}")
